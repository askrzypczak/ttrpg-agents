import { z } from "zod";

export interface Encounter {
  id: string;
  createdAt: number;
}

/** Source of truth for `MonsterInstance`; the protocol reuses it as the wire shape. */
export const monsterInstanceSchema = z.object({
  id: z.string(),
  encounterId: z.string(),
  monsterKey: z.string(),
  displayName: z.string(),
  maxHp: z.number(),
  currentHp: z.number(),
  initiative: z.number().nullable(),
  armorClass: z.number().nullable(),
  groupId: z.string().nullable(),
  createdAt: z.number(),
  /** Grid cells per side the monster's token spans. */
  footprint: z.number().int().min(1).default(1),
  /** Whether players see the instance's stats on the table; false = GM-only. */
  statsVisible: z.boolean(),
  /**
   * Where a new token for the instance is created, in scene units; null = the
   * extension's default row. Create-only: an existing token is never moved.
   */
  spawnPosition: z
    .object({ x: z.number(), y: z.number() })
    .nullable()
    .default(null),
});

export type MonsterInstance = z.infer<typeof monsterInstanceSchema>;

/** id, currentHp (starts at maxHp) and createdAt are generated by the store. */
export interface NewMonsterInstance {
  monsterKey: string;
  displayName: string;
  maxHp: number;
  initiative?: number | null;
  armorClass?: number | null;
  groupId?: string | null;
  /** Grid cells per side; defaults to 1. */
  footprint?: number;
  /** Defaults to false (GM-only). */
  statsVisible?: boolean;
  /** Where the token is created (scene units); defaults to null (the default row). */
  spawnPosition?: { x: number; y: number } | null;
}
